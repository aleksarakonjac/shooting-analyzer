-- Link lifecycle: pending -> active (only by the side that did not request) or ended;
-- active -> ended; ended is final. Re-linking is a brand-new request.
create function links_guard() returns trigger language plpgsql as $$
begin
  if new.status = old.status then
    return new;
  elsif old.status = 'pending' and new.status = 'active' and old.requested_by <> auth.uid() then
    return new;
  elsif old.status in ('pending', 'active') and new.status = 'ended' then
    return new;
  end if;
  raise exception 'invalid link status change' using errcode = '42501';
end $$;
create trigger links_guard before update of status on links
  for each row execute function links_guard();

alter table links drop constraint links_shooter_id_coach_id_key;
create unique index links_one_open on links (shooter_id, coach_id) where status <> 'ended';

